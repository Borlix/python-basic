# 24. Weekday Name: Input a number (1–7) and print the corresponding weekday name.

Num = int(input("Enter a num (1-7) : "))

if Num == 1:
    print("Sunday")
elif Num == 2:
    print("Monday")
elif Num == 3:
    print("Tuesday")
elif Num == 4:
    print("Weadnesday")
elif Num == 5:
    print("Thusday")
elif Num == 6:
    print("Friday")
elif Num == 7:
    print("Saturday")
else :
    print("NOT Exist, Plz enter number between 1-7")